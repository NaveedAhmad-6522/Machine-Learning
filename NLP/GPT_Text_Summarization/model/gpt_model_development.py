import tensorflow as tf

class GPTEmbedding(tf.keras.layers.Layer):
  def __init__(self,vocab_size,max_length,d_model):
    super().__init__()
    self.token_embedding=tf.keras.layers.Embedding(input_dim=vocab_size,output_dim=d_model)
    self.position_embedding = tf.keras.layers.Embedding(input_dim=max_length, output_dim=d_model)
  def call(self,input_ids):
    seq_length=tf.shape(input_ids)[1]
    positions=tf.range(start=0,limit=seq_length,delta=1)
    token_embeddings = self.token_embedding(input_ids)
    position_embeddings = self.position_embedding(positions)
    embeddings = token_embeddings + position_embeddings
    return embeddings

class MultiHeadAttention(tf.keras.layers.Layer):
  def __init__(self,d_model,num_heads):
    super().__init__()
    self.d_model = d_model
    self.num_heads = num_heads
    assert d_model % num_heads == 0
    self.head_dim = d_model // num_heads
    self.query=tf.keras.layers.Dense(d_model)
    self.keys=tf.keras.layers.Dense(d_model)
    self.values=tf.keras.layers.Dense(d_model)
    self.output_projection = tf.keras.layers.Dense(d_model)
    self.scale=tf.math.sqrt(tf.cast(self.head_dim, tf.float32))
  def split_heads(self,x):
    batch_size=tf.shape(x)[0]
    seq_length=tf.shape(x)[1]
    x=tf.reshape(x,(batch_size,seq_length,self.num_heads,self.head_dim))
    x=tf.transpose(x,perm=[0,2,1,3])
    return x
  def call(self, inputs, attention_mask=None):

    Q = self.query(inputs)
    K = self.keys(inputs)
    V = self.values(inputs)

    Q = self.split_heads(Q)
    K = self.split_heads(K)
    V = self.split_heads(V)

    scores = tf.matmul(Q, K, transpose_b=True)
    scaled_scores = scores / self.scale

    seq_length = tf.shape(inputs)[1]

    # Causal mask
    causal_mask = tf.linalg.band_part(
        tf.ones((seq_length, seq_length)),
        -1, 0
    )

    # Expand dimensions
    causal_mask = causal_mask[tf.newaxis, tf.newaxis, :, :]

    # Combine with padding mask
    if attention_mask is not None:
        padding_mask = attention_mask[:, tf.newaxis, tf.newaxis, :]

        combined_mask = tf.logical_and(
            tf.cast(causal_mask, tf.bool),
            tf.cast(padding_mask, tf.bool)
        )
    else:
        combined_mask = tf.cast(causal_mask, tf.bool)

    masked_scores = tf.where(
        combined_mask,
        scaled_scores,
        -1e9
    )

    attention_weights = tf.nn.softmax(masked_scores, axis=-1)

    output = tf.matmul(attention_weights, V)
    output = tf.transpose(output, perm=[0, 2, 1, 3])

    batch_size = tf.shape(inputs)[0]

    output = tf.reshape(
        output,
        (batch_size, seq_length, self.d_model)
    )

    output = self.output_projection(output)

    return output

