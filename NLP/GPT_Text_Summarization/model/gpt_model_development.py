class GPTDecoder(tf.keras.Model):
  def __init__(self,vocab_size,num_heads,max_length,d_model,dff,num_layers,dropout_rate=0.1):
    super().__init__()
    self.embedding=GPTEmbedding(vocab_size=vocab_size,max_length=max_length,d_model=d_model)
    self.transformer_block=[GPTTransformerBlock(d_model=d_model,num_heads=num_heads,dff=dff,dropout_rate=dropout_rate)for _ in range(num_layers)]
    self.final_layer_norm = tf.keras.layers.LayerNormalization(epsilon=1e-5 )
    self.lm_head = tf.keras.layers.Dense(vocab_size)
  def call(self, input_ids, training=False, attention_mask=None):
    x=self.embedding(input_ids)
    for block in self.transformer_block:
      x = block(
    x,
    training=training,
    attention_mask=attention_mask
)
    x = self.final_layer_norm(x)
    logits = self.lm_head(x)
    return logits

