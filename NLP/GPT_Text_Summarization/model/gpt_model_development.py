class GPTTransformerBlock(tf.keras.layers.Layer):
  def __init__(self,d_model,num_heads,dff,dropout_rate=0.1):
    super().__init__()
    self.attention=MultiHeadAttention(d_model, num_heads)
    self.ffn=FeedForwardNetwork(d_model,dff)
    self.layer_norm1=tf.keras.layers.LayerNormalization(epsilon=1e-5)
    self.layer_norm2=tf.keras.layers.LayerNormalization(epsilon=1e-5)
    self.dropout1 = tf.keras.layers.Dropout(dropout_rate)
    self.dropout2 = tf.keras.layers.Dropout(dropout_rate)
  def call(self, inputs, training=False, attention_mask=None):
    x = self.layer_norm1(inputs)
    attention_output = self.attention(
    x,
    attention_mask=attention_mask
)
    attention_output = self.dropout1(attention_output, training=training)
    x = inputs + attention_output
    normalized_x = self.layer_norm2(x)
    ffn_output = self.ffn(normalized_x)
    ffn_output = self.dropout2(ffn_output, training=training)
    output = x + ffn_output
    return output

